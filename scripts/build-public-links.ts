/**
 * Builds packages/core/src/knowledge/public-links.generated.ts: for every
 * corpus PDF, where a reader should be sent to open it.
 *
 * Indexed PDFs are stored with the source `pdf:<file name>`, which no browser
 * opens. This collects each file's published address from the manifests'
 * `url` fields (seed-corpus/manifest.json and any state manifests present
 * locally) and from seed-corpus/public-links.json (links found by hand for
 * documents that came without one).
 *
 * Usage: pnpm exec tsx scripts/build-public-links.ts
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CORPUS = resolve(ROOT, 'seed-corpus');
const OUT = resolve(ROOT, 'packages/core/src/knowledge/public-links.generated.ts');

interface ManifestDoc {
  file?: string;
  url?: string;
}

const links = new Map<string, string>();
const add = (file: string, url: string, from: string): void => {
  const name = file.split('/').pop()!;
  if (!/^https:\/\//.test(url)) throw new Error(`${from}: ${name} has a non-https link: ${url}`);
  const known = links.get(name);
  if (known && known !== url)
    console.warn(`  ! ${name}: keeping ${known}, ignoring ${url} (${from})`);
  if (!known) links.set(name, url);
};

const manifests = [
  resolve(CORPUS, 'manifest.json'),
  ...readdirSync(CORPUS, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => resolve(CORPUS, d.name, 'manifest.json'))
    .filter(existsSync),
];
for (const path of manifests) {
  const manifest = JSON.parse(readFileSync(path, 'utf8')) as { documents?: ManifestDoc[] };
  for (const doc of manifest.documents ?? []) {
    if (doc.file && doc.url) add(doc.file, doc.url, path);
  }
}

const extra = JSON.parse(readFileSync(resolve(CORPUS, 'public-links.json'), 'utf8')) as {
  links: Record<string, string>;
};
for (const [file, url] of Object.entries(extra.links)) add(file, url, 'public-links.json');

const entries = [...links.entries()].sort(([a], [b]) => a.localeCompare(b));
const source = [
  '// Generated by scripts/build-public-links.ts — do not edit by hand.',
  '// Corpus PDF file name → the address a reader can open.',
  '',
  'export const PUBLIC_LINKS: Readonly<Record<string, string>> = {',
  ...entries.map(([file, url]) => `  ${JSON.stringify(file)}: ${JSON.stringify(url)},`),
  '};',
  '',
].join('\n');
// Formatted the way the repo formats it, so a rebuild never leaves a format:check diff.
async function main(): Promise<void> {
  writeFileSync(OUT, await format(source, { ...(await resolveConfig(OUT)), filepath: OUT }));
  console.log(`Wrote ${entries.length} links from ${manifests.length} manifests to ${OUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
